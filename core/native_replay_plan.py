"""Build an immutable, auditable signal ledger for native engines.

The plan is not an executed LEAN or Nautilus backtest. It deliberately separates
point-in-time signal construction from execution, so both engines receive the
same bars/events/constraints. LIVE orders are never generated by this module.
"""
from __future__ import annotations
import hashlib,json
from bisect import bisect_right
from datetime import timezone
from pydantic import BaseModel,Field
from typing import Literal
from .market_data import normalize
from .replay_verify import VerificationRequest,PATTERN

class NativePlanRequest(VerificationRequest):
    engine:Literal['lean','nautilus']
    allocation_fraction:float=Field(default=0.1,gt=0,le=1)
    maximum_open_positions:int=Field(default=1,ge=1,le=20)


def build_plan(request:NativePlanRequest,dataset:dict)->dict:
    if dataset.get('symbol','').upper()!=request.symbol.upper():raise ValueError('Symbol/dataset mismatch')
    bars=normalize(dataset['bars'],allow_weekends=True)
    stamps=[b['date'] for b in bars]
    ledger=[];rejected=[];post_ids=set();seen_events=set()
    for event in sorted(request.events,key=lambda x:(x.first_observed_at,x.post_id,x.event_type)):
        serial=(event.post_id,event.event_type,event.first_observed_at.isoformat(),event.text)
        if serial in seen_events:continue
        seen_events.add(serial)
        stamp=event.first_observed_at.astimezone(timezone.utc).isoformat()
        base={'post_id':event.post_id,'author':event.author,'observed_utc':stamp,
              'source_kind':request.source_kind,'event_type':event.event_type,
              'text_sha256':hashlib.sha256(event.text.encode()).hexdigest()}
        if event.event_type!='new':
            rejected.append({**base,'reason':'revision_preserved_not_replayed_as_new_signal'});continue
        if event.post_id in post_ids:
            rejected.append({**base,'reason':'duplicate_post_id'});continue
        post_ids.add(event.post_id)
        match=PATTERN.search(event.text)
        if not match or match.group(2).upper()!=request.symbol.upper():
            rejected.append({**base,'reason':'no_matching_explicit_buy_sell'});continue
        enter=bisect_right(stamps,event.first_observed_at.date().isoformat())
        exit_idx=enter+request.horizon_sessions-1
        if exit_idx>=len(bars):
            rejected.append({**base,'reason':'future_bar_unavailable'});continue
        ledger.append({**base,'side':match.group(1).upper(),'symbol':request.symbol,
                       'entry_session':stamps[enter],'exit_session':stamps[exit_idx],
                       'entry_policy':'first_next_session_open','exit_policy':'N_session_close',
                       'allocation_fraction':request.allocation_fraction})
    payload={'schema':'talos.native_replay_plan.v1','native_engine_requested':request.engine,
             'execution_status':'PLAN_ONLY_NOT_EXECUTED','native_execution_verified':False,
             'source_authenticated':False,'market_data_verified':False,
             'model':'recommendation_ledger_next_session','symbol':request.symbol,'dataset_id':request.dataset_id,
             'fee_bps':request.fee_bps,'slippage_bps':request.slippage_bps,
             'horizon_sessions':request.horizon_sessions,'maximum_open_positions':request.maximum_open_positions,
             'signal_events':ledger,'excluded_or_revised':rejected,
             'bar_count':len(bars), 'bar_range':[stamps[0],stamps[-1]],
             'ohlcv_sha256':hashlib.sha256(json.dumps(bars,sort_keys=True,separators=(',',':')).encode()).hexdigest(),
             'no_lookahead_rule':'signals can execute only after UTC first_observed_at; no future market data in signal',
             'notifications_enabled':False,'live_trading_enabled':False,
             'requirements':['Native LEAN/Nautilus adapter for generic recommendations is not certified',
                             'Currency/calendar/corporate actions/short-sale/TP-SL/multiple overlapping signals need native evaluation',
                             'Use original unaltered bar series matched to this SHA256 for engine-level comparisons']}
    payload['plan_sha256']=hashlib.sha256(json.dumps(payload,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    return payload
